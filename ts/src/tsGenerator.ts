import type { EventDef, ParamDef, TrackingPlan } from './model.js';
import { headerFileName, oneLine, textLines } from './text.js';

/** First line of every generated TypeScript file. */
export const tsHeaderLine = '// GENERATED CODE - DO NOT MODIFY BY HAND.';

function jsdocLine(line: string): string {
  return line.replaceAll('*/', '*\\/');
}

function tsDoc(lines: readonly string[], indent: string): string {
  if (lines.length === 0) return '';
  if (lines.length === 1) return `${indent}/** ${jsdocLine(lines[0] ?? '')} */\n`;
  const body = lines.map((line) =>
    line === '' ? `${indent} *` : `${indent} * ${jsdocLine(line)}`,
  );
  return `${indent}/**\n${body.join('\n')}\n${indent} */\n`;
}

function tsType(param: ParamDef): string {
  switch (param.type) {
    case 'string':
      return 'string';
    case 'int':
    case 'double':
      return 'number';
    case 'bool':
      return 'boolean';
    case 'enum':
      return param.enumDef?.typeName ?? 'never';
    case 'list<string>':
      return 'readonly string[]';
  }
}

function method(event: EventDef, runtimeChecks: boolean): string {
  const lines: string[] = [];
  if (event.description !== undefined) lines.push(...textLines(event.description));
  if (event.owner !== undefined) {
    if (lines.length > 0) lines.push('');
    lines.push(`Owner: ${oneLine(event.owner)}`);
  }
  if (event.deprecated !== undefined) {
    if (lines.length > 0) lines.push('');
    const [first = '', ...rest] = textLines(event.deprecated);
    lines.push(`@deprecated ${first}`, ...rest);
  }
  let s = tsDoc(lines, '  ');
  if (event.params.length === 0) {
    return `${s}  ${event.identifier}(): void {\n    this._track('${event.name}', {});\n  }\n`;
  }

  const allOptional = event.params.every((p) => !p.required);
  const props = event.params
    .map((p) => {
      const doc = p.description === undefined ? '' : tsDoc(textLines(p.description), '    ');
      return (
        doc +
        (p.required
          ? `    ${p.identifier}: ${tsType(p)};`
          : `    ${p.identifier}?: ${tsType(p)} | undefined;`)
      );
    })
    .join('\n');
  s += `  ${event.identifier}(params: {\n${props}\n  }${allOptional ? ' = {}' : ''}): void {\n`;

  if (runtimeChecks) {
    for (const p of event.params) {
      const x = `params.${p.identifier}`;
      const guard = p.required ? '' : `${x} !== undefined && `;
      const check = (condition: string, message: string) => {
        s += `    if (${guard}${condition}) {\n      throw new RangeError('${message}');\n    }\n`;
      };
      if (p.type === 'int') check(`!Number.isInteger(${x})`, `${p.identifier} must be an integer`);
      if (p.min !== undefined) check(`!(${x} >= ${p.min})`, `${p.identifier} must be >= ${p.min}`);
      if (p.max !== undefined) check(`!(${x} <= ${p.max})`, `${p.identifier} must be <= ${p.max}`);
      if (p.maxLength !== undefined) {
        check(
          `${x}.length > ${p.maxLength}`,
          `${p.identifier} must be at most ${p.maxLength} characters`,
        );
      }
    }
  }

  const required = event.params.filter((p) => p.required);
  const optional = event.params.filter((p) => !p.required);
  const entry = (p: ParamDef) => `      ${p.name}: params.${p.identifier},`;
  if (optional.length === 0) {
    s += `    this._track('${event.name}', {\n${required.map(entry).join('\n')}\n    });\n  }\n`;
    return s;
  }
  s +=
    required.length > 0
      ? `    const payload: Record<string, AnalyticsValue> = {\n${required.map(entry).join('\n')}\n    };\n`
      : '    const payload: Record<string, AnalyticsValue> = {};\n';
  for (const p of optional) {
    s += `    if (params.${p.identifier} !== undefined) {\n      payload['${p.name}'] = params.${p.identifier};\n    }\n`;
  }
  s += `    this._track('${event.name}', payload);\n  }\n`;
  return s;
}

/**
 * Generates the TypeScript file for a plan (SPEC.md sections 7.1, 7.3, 7.5).
 * `planPath` is only used for its base name in the header.
 */
export function generateTypescript(plan: TrackingPlan, planPath: string): string {
  const out: string[] = [];
  out.push(`${tsHeaderLine}
// Generated by trackplan from ${headerFileName(planPath)}. Run \`npx trackplan generate\` to update.

/* eslint-disable */

/** A value that can be sent as an event param. */
export type AnalyticsValue = string | number | boolean | readonly string[];

/** The read-only params object passed to adapters. */
export type AnalyticsParams = Readonly<Record<string, AnalyticsValue>>;

/**
 * Receives every tracked event. Implement it to forward events to an
 * analytics backend such as Firebase Analytics, PostHog or your own API.
 */
export interface AnalyticsAdapter {
  /** Sends \`event\` with its \`params\` to the backend. */
  track(event: string, params: AnalyticsParams): void;
}
`);
  for (const e of plan.enums) {
    const doc = e.description === undefined ? '' : tsDoc(textLines(e.description), '');
    out.push(
      `${doc}export type ${e.typeName} = ${e.values.map((v) => `'${v.name}'`).join(' | ')};\n`,
    );
  }
  const methods = plan.events.map((e) => method(e, plan.typescriptRuntimeChecks));
  out.push(`/** Type-safe analytics events generated from the tracking plan. */
export class ${plan.typescriptClassName} {
  private readonly _adapters: readonly AnalyticsAdapter[];

  /** Creates an instance that sends every event to all \`adapters\`. */
  constructor(adapters: readonly AnalyticsAdapter[]) {
    this._adapters = [...adapters];
  }

${methods.join('\n')}
  private _track(event: string, params: Record<string, AnalyticsValue>): void {
    const copy: Record<string, AnalyticsValue> = {};
    for (const [key, value] of Object.entries(params)) {
      copy[key] = typeof value === 'object' ? Object.freeze([...value]) : value;
    }
    const payload: AnalyticsParams = Object.freeze(copy);
    for (const adapter of this._adapters) {
      adapter.track(event, payload);
    }
  }
}

/** Stores tracked events in memory so tests can assert on them. */
export class RecordingAnalyticsAdapter implements AnalyticsAdapter {
  /** Tracked events, oldest first. */
  readonly events: { event: string; params: AnalyticsParams }[] = [];

  track(event: string, params: AnalyticsParams): void {
    this.events.push({ event, params });
  }

  /** Removes all recorded events. */
  clear(): void {
    this.events.length = 0;
  }
}

/** Passes one readable line per event to \`log\`, for example \`console.log\`. */
export class DebugAnalyticsAdapter implements AnalyticsAdapter {
  private readonly _log: (message: string) => void;

  /** Creates an adapter that writes each event to \`log\`. */
  constructor(log: (message: string) => void) {
    this._log = log;
  }

  track(event: string, params: AnalyticsParams): void {
    this._log(\`\${event} \${JSON.stringify(params)}\`);
  }
}
`);
  return out.join('\n');
}
