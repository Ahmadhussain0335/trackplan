import 'model.dart';
import 'text.dart';

/// Start of the first line of every generated docs file.
const docsHeaderPrefix = '<!-- Generated by trackplan';

String _html(String text) => text
    .replaceAll('&', '&amp;')
    .replaceAll('<', '&lt;')
    .replaceAll('>', '&gt;');

String _cell(String? text) {
  if (text == null || text.isEmpty) return '-';
  return textLines(
    text,
  ).map((line) => _html(line).replaceAll('|', r'\|')).join('<br>');
}

final _fence = RegExp(r'^( {0,3})(```|~~~)');

// A code fence in a description would swallow the rest of the catalog.
String _paragraphLine(String line) =>
    _html(line).replaceFirstMapped(_fence, (m) => '${m[1]}\\${m[2]}');

String _paragraph(String text) =>
    textLines(text).map(_paragraphLine).join('\n');

String _code(String name) => '`$name`';

/// Generates the Markdown event catalog for [plan] (SPEC.md section 8).
///
/// [planPath] is only used for its base name in the header.
String generateDocs(TrackingPlan plan, String planPath) {
  final o = <String>[
    '$docsHeaderPrefix from ${headerFileName(planPath)}. '
        'Do not edit by hand. -->',
    '',
    '# ${plan.name == null ? 'Tracking plan' : _html(oneLine(plan.name!))}',
    '',
  ];
  final description = plan.description;
  if (description != null) o.addAll([_paragraph(description), '']);
  o.addAll([
    'Events: ${plan.events.length}. Enums: ${plan.enums.length}.',
    '',
    '## Events',
    '',
    '| Event | Description | Owner | Tags | Status |',
    '| --- | --- | --- | --- | --- |',
  ]);
  for (final event in plan.events) {
    final tags = event.tags.isEmpty
        ? '-'
        : event.tags.map((t) => _cell(oneLine(t))).join(', ');
    final owner = event.owner == null ? '-' : _cell(oneLine(event.owner!));
    final status = event.deprecated == null ? 'Active' : 'Deprecated';
    o.add(
      '| ${_code(event.name)} | ${_cell(event.description)} | $owner | '
      '$tags | $status |',
    );
  }
  o.add('');

  for (final event in plan.events) {
    o.addAll(['### ${_code(event.name)}', '']);
    final eventDescription = event.description;
    o.addAll([
      eventDescription == null
          ? '_No description._'
          : _paragraph(eventDescription),
      '',
    ]);
    final deprecated = event.deprecated;
    if (deprecated != null) {
      o.addAll(['**Deprecated:** ${_paragraph(deprecated)}', '']);
    }
    final details = [
      if (event.owner != null) '- Owner: ${_html(oneLine(event.owner!))}',
      if (event.tags.isNotEmpty)
        '- Tags: ${event.tags.map((t) => _html(oneLine(t))).join(', ')}',
    ];
    if (details.isNotEmpty) o.addAll([...details, '']);
    if (event.params.isEmpty) {
      o.addAll(['No parameters.', '']);
      continue;
    }
    o.addAll([
      '| Param | Type | Required | Constraints | Description |',
      '| --- | --- | --- | --- | --- |',
    ]);
    for (final param in event.params) {
      final enumDef = param.enumDef;
      final type = enumDef == null
          ? _code(param.type.planName)
          : '${_code(enumDef.name)} (enum)';
      final constraints = [
        if (param.min != null) 'min ${param.min}',
        if (param.max != null) 'max ${param.max}',
        if (param.maxLength != null) 'max length ${param.maxLength}',
        if (enumDef != null)
          'one of ${enumDef.values.map((v) => _code(v.name)).join(', ')}',
      ];
      o.add(
        '| ${_code(param.name)} | $type | ${param.required ? 'yes' : 'no'} | '
        '${constraints.isEmpty ? '-' : constraints.join(', ')} | '
        '${_cell(param.description)} |',
      );
    }
    o.add('');
  }

  if (plan.enums.isNotEmpty) {
    o.addAll(['## Enums', '']);
    for (final enumDef in plan.enums) {
      o.addAll(['### ${_code(enumDef.name)}', '']);
      final enumDescription = enumDef.description;
      if (enumDescription != null) o.addAll([_paragraph(enumDescription), '']);
      o.addAll([
        'Values: ${enumDef.values.map((v) => _code(v.name)).join(', ')}',
        '',
      ]);
      final usedBy = [
        for (final event in plan.events)
          for (final param in event.params)
            if (param.enumDef == enumDef) _code('${event.name}.${param.name}'),
      ];
      o.addAll([
        usedBy.isEmpty
            ? 'Not used by any param.'
            : 'Used by: ${usedBy.join(', ')}',
        '',
      ]);
    }
  }
  var text = o.join('\n');
  var end = text.length;
  while (end > 0 && text.codeUnitAt(end - 1) == 0x0A) {
    end--;
  }
  return '${text.substring(0, end)}\n';
}
