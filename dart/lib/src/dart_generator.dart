import 'package:dart_style/dart_style.dart';
import 'package:pub_semver/pub_semver.dart';

import 'model.dart';
import 'text.dart';

/// First line of every generated Dart file.
const dartHeaderLine = '// GENERATED CODE - DO NOT MODIFY BY HAND.';

// Pinned so that the output does not change with the formatter's latest
// language version. Generated code uses null-aware elements (Dart 3.8).
final _formatter = DartFormatter(
  languageVersion: Version(3, 8, 0),
  lineEnding: '\n',
);

const _lintIgnore = '// ignore_for_file: type=lint\n';

/// Generates the Dart file for [plan] (SPEC.md sections 7.1, 7.2 and 7.5).
///
/// [planPath] is only used for its base name in the header.
String generateDart(TrackingPlan plan, String planPath) {
  final out = StringBuffer()
    ..writeln(dartHeaderLine)
    ..writeln(
      '// Generated by trackplan from ${headerFileName(planPath)}. '
      'Run `dart run trackplan generate` to update.',
    )
    ..writeln()
    ..write(_lintIgnore)
    ..writeln()
    ..writeln(_adapterInterface);

  for (final enumDef in plan.enums) {
    out
      ..writeln()
      ..write(_enum(enumDef));
  }

  out
    ..writeln()
    ..writeln(
      '/// Type-safe analytics events generated from the tracking plan.',
    )
    ..writeln('class ${plan.dartClassName} {')
    ..writeln(
      '  /// Creates an instance that sends every event to all [adapters].',
    )
    ..writeln(
      '  ${plan.dartClassName}(List<AnalyticsAdapter> adapters) '
      ': _adapters = List.unmodifiable(adapters);',
    )
    ..writeln()
    ..writeln('  final List<AnalyticsAdapter> _adapters;');
  for (final event in plan.events) {
    out
      ..writeln()
      ..write(_method(event));
  }
  out
    ..writeln()
    ..write(_trackMethod)
    ..writeln('}')
    ..writeln()
    ..write(_helperClasses);

  final formatted = _formatter.format(out.toString());
  // Added after formatting, because the marker also stops our own formatter.
  return formatted.replaceFirst(
    _lintIgnore,
    '$_lintIgnore// dart format off\n',
  );
}

const _adapterInterface = '''
/// Receives every tracked event. Implement it to forward events to an
/// analytics backend such as Firebase Analytics, PostHog or your own API.
abstract interface class AnalyticsAdapter {
  /// Sends [event] with its [params] to the backend.
  void track(String event, Map<String, Object> params);
}''';

const _trackMethod = r'''
  void _track(String event, Map<String, Object> params) {
    final payload = Map<String, Object>.unmodifiable({
      for (final MapEntry(:key, :value) in params.entries)
        key: value is List<String> ? List<String>.unmodifiable(value) : value,
    });
    for (final adapter in _adapters) {
      adapter.track(event, payload);
    }
  }
''';

const _helperClasses = r'''
/// Stores tracked events in memory so tests can assert on them.
class RecordingAnalyticsAdapter implements AnalyticsAdapter {
  /// Tracked events, oldest first.
  final List<({String event, Map<String, Object> params})> events = [];

  @override
  void track(String event, Map<String, Object> params) {
    events.add((event: event, params: params));
  }

  /// Removes all recorded events.
  void clear() => events.clear();
}

/// Passes one readable line per event to [log], for example `debugPrint`.
class DebugAnalyticsAdapter implements AnalyticsAdapter {
  /// Creates an adapter that writes each event to [log].
  DebugAnalyticsAdapter(this.log);

  /// Receives one line per tracked event.
  final void Function(String message) log;

  @override
  void track(String event, Map<String, Object> params) {
    log('$event $params');
  }
}
''';

String _docComment(List<String> lines, String indent) => lines
    .map((line) => line.isEmpty ? '$indent///\n' : '$indent/// $line\n')
    .join();

/// A single-quoted Dart string literal (SPEC.md section 7.6).
String dartStringLiteral(String text) {
  final escaped = text
      .replaceAll(r'\', r'\\')
      .replaceAll("'", r"\'")
      .replaceAll(r'$', r'\$')
      .replaceAll('\n', r'\n')
      .replaceAll('\t', r'\t');
  return "'$escaped'";
}

String _enum(EnumDef enumDef) {
  final out = StringBuffer();
  final description = enumDef.description;
  if (description != null) out.write(_docComment(textLines(description), ''));
  out.writeln('enum ${enumDef.typeName} {');
  for (final (i, value) in enumDef.values.indexed) {
    final end = i == enumDef.values.length - 1 ? ';' : ',';
    out.writeln('  ${value.identifier}(${dartStringLiteral(value.name)})$end');
  }
  out
    ..writeln()
    ..writeln('  const ${enumDef.typeName}(this.value);')
    ..writeln()
    ..writeln('  /// The value sent to analytics.')
    ..writeln('  final String value;')
    ..writeln('}');
  return out.toString();
}

String _dartType(ParamDef param) => switch (param.type) {
  ParamType.string => 'String',
  ParamType.int_ => 'int',
  ParamType.double_ => 'double',
  ParamType.bool_ => 'bool',
  ParamType.enum_ => param.enumDef!.typeName,
  ParamType.stringList => 'List<String>',
};

String _method(EventDef event) {
  final lines = <String>[];
  final description = event.description;
  if (description != null) lines.addAll(textLines(description));
  final owner = event.owner;
  if (owner != null) {
    if (lines.isNotEmpty) lines.add('');
    lines.add('Owner: ${oneLine(owner)}');
  }
  final described = event.params.where((p) => p.description != null).toList();
  if (described.isNotEmpty) {
    if (lines.isNotEmpty) lines.add('');
    lines.add('Parameters:');
    for (final param in described) {
      final [first, ...rest] = textLines(param.description!);
      lines.add('- `${param.identifier}`: $first');
      lines.addAll(rest.map((line) => line.isEmpty ? '' : '  $line'));
    }
  }

  final out = StringBuffer(_docComment(lines, '  '));
  final deprecated = event.deprecated;
  if (deprecated != null) {
    out.writeln(
      '  @Deprecated(${dartStringLiteral(textLines(deprecated).join('\n'))})',
    );
  }
  if (event.params.isEmpty) {
    out
      ..writeln('  void ${event.identifier}() {')
      ..writeln("    _track('${event.name}', const {});")
      ..writeln('  }');
    return out.toString();
  }

  out.writeln('  void ${event.identifier}({');
  for (final param in event.params) {
    out.writeln(
      param.required
          ? '    required ${_dartType(param)} ${param.identifier},'
          : '    ${_dartType(param)}? ${param.identifier},',
    );
  }
  out.writeln('  }) {');
  for (final param in event.params) {
    final id = param.identifier;
    final guard = param.required ? '' : '$id == null || ';
    if (param.min != null) {
      out.writeln(
        "    assert($guard$id >= ${param.min}, '$id must be >= ${param.min}');",
      );
    }
    if (param.max != null) {
      out.writeln(
        "    assert($guard$id <= ${param.max}, '$id must be <= ${param.max}');",
      );
    }
    if (param.maxLength != null) {
      out.writeln(
        "    assert($guard$id.length <= ${param.maxLength}, "
        "'$id must be at most ${param.maxLength} characters');",
      );
    }
  }
  out.writeln("    _track('${event.name}', {");
  for (final param in event.params) {
    final id = param.identifier;
    final isEnum = param.type == ParamType.enum_;
    if (param.required) {
      out.writeln("      '${param.name}': ${isEnum ? '$id.value' : id},");
    } else {
      out.writeln("      '${param.name}': ?${isEnum ? '$id?.value' : id},");
    }
  }
  out
    ..writeln('    });')
    ..writeln('  }');
  return out.toString();
}
