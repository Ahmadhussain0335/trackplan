import type { TrackingPlan } from './model.js';
import { headerFileName, oneLine, textLines } from './text.js';

/** Start of the first line of every generated docs file. */
export const docsHeaderPrefix = '<!-- Generated by trackplan';

function html(text: string): string {
  return text.replaceAll('&', '&amp;').replaceAll('<', '&lt;').replaceAll('>', '&gt;');
}

function cell(text: string | undefined): string {
  if (text === undefined || text === '') return '-';
  return textLines(text)
    .map((line) => html(line).replaceAll('|', '\\|'))
    .join('<br>');
}

const fence = /^( {0,3})(```|~~~)/;

// A code fence in a description would swallow the rest of the catalog.
function paragraphLine(line: string): string {
  return html(line).replace(fence, (_, indent: string, marker: string) => `${indent}\\${marker}`);
}

function paragraph(text: string): string {
  return textLines(text).map(paragraphLine).join('\n');
}

const code = (name: string) => `\`${name}\``;

/**
 * Generates the Markdown event catalog for a plan (SPEC.md section 8).
 * `planPath` is only used for its base name in the header.
 */
export function generateDocs(plan: TrackingPlan, planPath: string): string {
  const o: string[] = [
    `${docsHeaderPrefix} from ${headerFileName(planPath)}. Do not edit by hand. -->`,
    '',
    `# ${plan.name === undefined ? 'Tracking plan' : html(oneLine(plan.name))}`,
    '',
  ];
  if (plan.description !== undefined) o.push(paragraph(plan.description), '');
  o.push(
    `Events: ${plan.events.length}. Enums: ${plan.enums.length}.`,
    '',
    '## Events',
    '',
    '| Event | Description | Owner | Tags | Status |',
    '| --- | --- | --- | --- | --- |',
  );
  for (const event of plan.events) {
    const tags = event.tags.length === 0 ? '-' : event.tags.map((t) => cell(oneLine(t))).join(', ');
    const owner = event.owner === undefined ? '-' : cell(oneLine(event.owner));
    const status = event.deprecated === undefined ? 'Active' : 'Deprecated';
    o.push(`| ${code(event.name)} | ${cell(event.description)} | ${owner} | ${tags} | ${status} |`);
  }
  o.push('');

  for (const event of plan.events) {
    o.push(`### ${code(event.name)}`, '');
    o.push(
      event.description === undefined ? '_No description._' : paragraph(event.description),
      '',
    );
    if (event.deprecated !== undefined)
      o.push(`**Deprecated:** ${paragraph(event.deprecated)}`, '');
    const details: string[] = [];
    if (event.owner !== undefined) details.push(`- Owner: ${html(oneLine(event.owner))}`);
    if (event.tags.length > 0)
      details.push(`- Tags: ${event.tags.map((t) => html(oneLine(t))).join(', ')}`);
    if (details.length > 0) o.push(...details, '');
    if (event.params.length === 0) {
      o.push('No parameters.', '');
      continue;
    }
    o.push(
      '| Param | Type | Required | Constraints | Description |',
      '| --- | --- | --- | --- | --- |',
    );
    for (const param of event.params) {
      const enumDef = param.enumDef;
      const type = enumDef === undefined ? code(param.type) : `${code(enumDef.name)} (enum)`;
      const constraints: string[] = [];
      if (param.min !== undefined) constraints.push(`min ${param.min}`);
      if (param.max !== undefined) constraints.push(`max ${param.max}`);
      if (param.maxLength !== undefined) constraints.push(`max length ${param.maxLength}`);
      if (enumDef !== undefined)
        constraints.push(`one of ${enumDef.values.map((v) => code(v.name)).join(', ')}`);
      o.push(
        `| ${code(param.name)} | ${type} | ${param.required ? 'yes' : 'no'} | ` +
          `${constraints.length === 0 ? '-' : constraints.join(', ')} | ${cell(param.description)} |`,
      );
    }
    o.push('');
  }

  if (plan.enums.length > 0) {
    o.push('## Enums', '');
    for (const enumDef of plan.enums) {
      o.push(`### ${code(enumDef.name)}`, '');
      if (enumDef.description !== undefined) o.push(paragraph(enumDef.description), '');
      o.push(`Values: ${enumDef.values.map((v) => code(v.name)).join(', ')}`, '');
      const usedBy = plan.events.flatMap((event) =>
        event.params
          .filter((p) => p.enumDef === enumDef)
          .map((p) => code(`${event.name}.${p.name}`)),
      );
      o.push(usedBy.length === 0 ? 'Not used by any param.' : `Used by: ${usedBy.join(', ')}`, '');
    }
  }
  const text = o.join('\n');
  let end = text.length;
  while (end > 0 && text.charCodeAt(end - 1) === 0x0a) end--;
  return `${text.slice(0, end)}\n`;
}
