import 'dart:convert';

import 'package:test/test.dart';
import 'dart:io';

import 'package:path/path.dart' as p;
import 'package:trackplan/src/dart_generator.dart';
import 'package:trackplan/src/names.dart';
import 'package:trackplan/src/text.dart';
import 'package:trackplan/trackplan.dart';

TrackingPlan _plan(String yaml) {
  final result = validatePlan(utf8.encode(yaml));
  expect(result.hasErrors, isFalse, reason: '${result.diagnostics}');
  return result.plan!;
}

void main() {
  group('dartStringLiteral', () {
    test('escapes backslash, quote, dollar, line feed and tab', () {
      expect(dartStringLiteral("a\\b'c\$d\ne\tf"), r"'a\\b\'c\$d\ne\tf'");
    });
  });

  group('textLines', () {
    test('normalizes CRLF and trims trailing spaces and tabs only', () {
      expect(textLines('\n\na \t\r\n b\n\n'), ['a', ' b']);
    });

    test('is fast on long runs of spaces', () {
      final watch = Stopwatch()..start();
      expect(textLines('a${' ' * 200000}b${' ' * 200000}'), [
        'a${' ' * 200000}b',
      ]);
      expect(watch.elapsed, lessThan(const Duration(seconds: 2)));
    });

    test('keeps inner blank lines', () {
      expect(textLines('a\n\nb'), ['a', '', 'b']);
    });
  });

  group('headerFileName', () {
    test('uses the base name with either separator', () {
      expect(headerFileName('config/plan.yaml'), 'plan.yaml');
      expect(headerFileName(r'config\plan.yaml'), 'plan.yaml');
    });

    test('replaces characters that could break the header comment', () {
      expect(headerFileName('a\nb*?.yaml'), 'a_b__.yaml');
    });
  });

  group('generateDart', () {
    const yaml = '''
version: 1
events:
  a:
    description: |
      Text with // dart format on and */ in it.
''';

    test('is deterministic', () {
      final plan = _plan(yaml);
      expect(generateDart(plan, 'p.yaml'), generateDart(_plan(yaml), 'p.yaml'));
    });

    test('ends with exactly one line feed and uses LF only', () {
      final code = generateDart(_plan(yaml), 'p.yaml');
      expect(code, endsWith('}\n'));
      expect(code, isNot(endsWith('\n\n')));
      expect(code, isNot(contains('\r')));
    });

    test('adds the format-off marker once, after the lint ignore', () {
      final code = generateDart(_plan(yaml), 'p.yaml');
      expect(
        code,
        contains('// ignore_for_file: type=lint\n// dart format off\n'),
      );
      expect('// dart format off'.allMatches(code), hasLength(1));
    });

    test('keeps a format marker in a description inside the doc comment', () {
      final code = generateDart(_plan(yaml), 'p.yaml');
      expect(
        code,
        contains('  /// Text with // dart format on and */ in it.\n'),
      );
      expect(code, isNot(contains('\n// dart format on')));
    });

    test('names the plan file in the header', () {
      final code = generateDart(_plan(yaml), 'some/dir/my_plan.yaml');
      expect(
        code.split('\n')[1],
        '// Generated by trackplan from my_plan.yaml. '
        'Run `dart run trackplan generate` to update.',
      );
    });
  });

  test('every type name the generated code uses is reserved (SPEC 4.5)', () {
    final dir = p.join('..', 'fixtures', 'valid', 'shop_app');
    final plan = validatePlan(
      File(p.join(dir, 'plan.yaml')).readAsBytesSync(),
    ).plan!;
    final code = generateDart(plan, 'plan.yaml')
        .split('\n')
        .where((line) => !line.trimLeft().startsWith('//'))
        .join('\n')
        .replaceAll(RegExp(r"'[^'\n]*'"), "''");
    final defined = {plan.dartClassName, ...plan.enums.map((e) => e.typeName)};
    final used = RegExp(
      r'\b[A-Z][A-Za-z0-9]*\b',
    ).allMatches(code).map((m) => m[0]!).toSet().difference(defined);
    expect(used, isNotEmpty);
    expect(used.difference(reservedTypeNames), isEmpty);
  });

  group('generateDocs', () {
    test('uses the default title and handles a plan without enums', () {
      final docs = generateDocs(
        _plan('version: 1\nevents:\n  a: {description: d}\n'),
        'p.yaml',
      );
      expect(docs, contains('\n# Tracking plan\n'));
      expect(docs, isNot(contains('## Enums')));
      expect(docs, endsWith('No parameters.\n'));
    });

    test('neutralizes code fences in descriptions', () {
      final docs = generateDocs(
        _plan(
          'version: 1\nevents:\n  a:\n    description: |\n      ```\n      ~~~ x\n',
        ),
        'p.yaml',
      );
      expect(docs, contains('\n\\```\n\\~~~ x\n'));
    });

    test('escapes HTML in titles and cells', () {
      final docs = generateDocs(
        _plan(
          'version: 1\nmeta: {name: "<b>&"}\n'
          'events:\n  a: {description: "x | <i>"}\n',
        ),
        'p.yaml',
      );
      expect(docs, contains('# &lt;b&gt;&amp;\n'));
      expect(docs, contains(r'| x \| &lt;i&gt; |'));
    });
  });
}
